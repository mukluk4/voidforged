# Class armor sets for dynamic items: one set per class, one dynamic item per visible slot, an armor set
# with bonuses at 2/4/8 pieces, and a token vendor that sells them.
#
#   python gen_class_sets.py <eqemu_config.json> export <class_sets.json>   # write settings from the live DB
#   python gen_class_sets.py <eqemu_config.json> sql <class_sets.json> <out.sql>
#
# class_sets.json holds every choice (see "export" for this server's values):
#   shell_item       a stat-less item to copy (aug slots, No Trade, flags); its stats must be 0
#   item_id_base     piece item id = item_id_base + piece.block + class id (e.g. 900000 + 300 + 12)
#   set_id_base      armor set id = set_id_base + class id
#   pieces           [{block, name, look_item, stat_multiplier}] look_item gives slot, model and icon
#   classes          {class id: theme}  -> items are "<theme> <piece name>"
#   affixes          {min, max} random affixes per piece
#   vendor           {merchant_id, cost (alternate currency), first_slot}
#   bonuses          {class id: [{pieces, affix | stat_id, value}]} (affix codes as in dynamic_affix_pool)
import json, os, subprocess, sys

cfg = json.load(open(sys.argv[1]))['server']['database']
mode = sys.argv[2]
env = dict(os.environ, MYSQL_PWD=cfg['password'])
mysql = os.environ.get('MYSQL_EXE', r'C:\Program Files\MariaDB 12.3\bin\mysql.exe')


def query(sql):
    out = subprocess.run([mysql, '-h', cfg['host'], '-P', str(cfg['port']), '-u', cfg['username'], cfg['db'],
                          '-N', '-B', '-e', sql], env=env, capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines()]


if mode == 'export':
    # This server's sets: pieces 9002xx-9009xx (blocks 200..900), sets 101-116, vendor 1200010.
    # Piece order = the vendor's order for each class (Helm ... Boots).
    out_path = sys.argv[3]
    pieces = [
        {'block': 300, 'name': 'Helm', 'look_item': 1001},
        {'block': 400, 'name': 'Chestguard', 'look_item': 1004},
        {'block': 600, 'name': 'Sleeves', 'look_item': 1008},
        {'block': 700, 'name': 'Bracer', 'look_item': 1009},
        {'block': 800, 'name': 'Gloves', 'look_item': 1010},
        {'block': 900, 'name': 'Leggings', 'look_item': 1011},
        {'block': 200, 'name': 'Boots', 'look_item': 1012},
    ]
    mult = {int(i) // 100 * 100 - 900000: float(m) for i, m in
            query("SELECT item_id, stat_multiplier FROM dynamic_items WHERE item_id BETWEEN 900201 AND 900916")}
    for p in pieces:
        p['stat_multiplier'] = mult[p['block']]
    classes = {}
    for item_id, name in query("SELECT id, Name FROM items WHERE id BETWEEN 900201 AND 900216"):
        classes[str(int(item_id) - 900200)] = name.rsplit(' ', 1)[0]
    affix_counts = query("SELECT MIN(min_affixes), MAX(max_affixes) FROM dynamic_items WHERE item_id BETWEEN 900201 AND 900916")[0]
    vendor = query("SELECT merchantid, MIN(alt_currency_cost), MIN(slot) FROM merchantlist "
                   "WHERE item BETWEEN 900201 AND 900916 GROUP BY merchantid")[0]
    bonuses = {}
    for set_id, pc, stat_id, affix, value in query(
            "SELECT set_id, min_pieces, stat_id, affix, stat_value FROM armor_set_bonuses "
            "WHERE set_id BETWEEN 101 AND 116 ORDER BY set_id, min_pieces, id"):
        b = {'pieces': int(pc), 'value': int(value)}
        b.update({'affix': affix} if affix else {'stat_id': int(stat_id)})
        bonuses.setdefault(str(int(set_id) - 100), []).append(b)
    settings = {
        'shell_item': 900101, 'item_id_base': 900000, 'set_id_base': 100,
        'pieces': pieces, 'classes': classes,
        'affixes': {'min': int(affix_counts[0]), 'max': int(affix_counts[1])},
        'vendor': {'merchant_id': int(vendor[0]), 'cost': int(vendor[1]), 'first_slot': int(vendor[2])},
        'bonuses': bonuses,
    }
    json.dump(settings, open(out_path, 'w'), indent=2)
    print('wrote', out_path)
    sys.exit(0)

# --- sql ---
s = json.load(open(sys.argv[3]))
out_path = sys.argv[4]
item_cols = [r[0] for r in query("SELECT column_name FROM information_schema.columns WHERE table_schema = DATABASE() "
                                 "AND table_name = 'items' ORDER BY ordinal_position")]
LOOK_COLS = ['slots', 'material', 'icon', 'idfile', 'weight', 'size']

items = []                                    # (id, class id, piece)
for cid in sorted(s['classes'], key=int):
    for p in s['pieces']:
        items.append((s['item_id_base'] + p['block'] + int(cid), int(cid), p))
ids = ', '.join(str(i) for i, _, _ in items)
set_ids = ', '.join(str(s['set_id_base'] + int(c)) for c in s['classes'])
v = s['vendor']

sql = ['-- Class armor sets. GENERATED by gen_class_sets.py from class_sets.json', 'START TRANSACTION;', '',
       f'DELETE FROM merchantlist WHERE merchantid = {v["merchant_id"]} AND item IN ({ids});',
       f'DELETE FROM armor_set_bonuses WHERE set_id IN ({set_ids});',
       f'DELETE FROM armor_set_items WHERE item_id IN ({ids});',
       f'DELETE FROM dynamic_items WHERE item_id IN ({ids});',
       f'DELETE FROM items WHERE id IN ({ids});', '']

for item_id, cid, p in items:
    name = f"{s['classes'][str(cid)]} {p['name']}"
    over = {'id': str(item_id), 'Name': json.dumps(name).replace('"', "'"), 'lore': json.dumps(name).replace('"', "'"),
            'classes': str(1 << (cid - 1))}
    for c in LOOK_COLS:
        over[c] = f'(SELECT `{c}` FROM (SELECT * FROM items WHERE id = {p["look_item"]}) look)'
    # Class look: armor texture and one tint for the whole set (a robe for caster chests)
    look = s.get('looks', {}).get(str(cid))
    if look:
        over['material'] = str(look.get('chest_material', look['material']) if p['name'] == 'Chestguard' else look['material'])
        over['color'] = str(0xFF000000 | int(look['color'], 16))
    cols = ', '.join(f'`{c}`' for c in item_cols)
    vals = ', '.join(over.get(c, f'`{c}`') for c in item_cols)
    sql.append(f'INSERT INTO items ({cols}) SELECT {vals} FROM items WHERE id = {s["shell_item"]};')
sql.append('')

sql.append('INSERT INTO dynamic_items (item_id, class_id, tier, min_affixes, max_affixes, stat_multiplier, notes) VALUES')
sql.append(',\n'.join(f"({i}, {c}, 1, {s['affixes']['min']}, {s['affixes']['max']}, {p['stat_multiplier']}, 'Class set piece')"
                      for i, c, p in items) + ';')
sql.append('INSERT INTO armor_set_items (item_id, set_id, class_mask) VALUES')
sql.append(',\n'.join(f'({i}, {s["set_id_base"] + c}, 0)' for i, c, _ in items) + ';')

rows = []
for cid, blist in sorted(s['bonuses'].items(), key=lambda kv: int(kv[0])):
    for b in blist:
        rows.append(f"({s['set_id_base'] + int(cid)}, {b['pieces']}, 0, {b.get('stat_id', 0)}, "
                    f"'{b.get('affix', '')}', {b['value']})")
sql.append('INSERT INTO armor_set_bonuses (set_id, min_pieces, class_mask, stat_id, affix, stat_value) VALUES')
sql.append(',\n'.join(rows) + ';')

# Vendor: in class order, pieces in the listed order; only that class can see each piece
sql.append('INSERT INTO merchantlist (merchantid, slot, item, alt_currency_cost, classes_required) VALUES')
sql.append(',\n'.join(f'({v["merchant_id"]}, {v["first_slot"] + n}, {i}, {v["cost"]}, {1 << (c - 1)})'
                      for n, (i, c, _) in enumerate(items)) + ';')
sql += ['', 'COMMIT;']
open(out_path, 'w', newline='\n').write('\n'.join(sql) + '\n')
print(f'{len(items)} pieces, {len(rows)} bonus rows -> {out_path}')
