# Tiered rift gear (docs/dynamic_items/TIERED_GEAR.md): armor for gear tiers 2-5, non-visible pieces and
# augments for tiers 1-5, their sets and bonuses, custom server-side spells, and the tier vendors.
#
#   python gen_tier_gear.py <eqemu_config.json> <class_sets.json> <tier_gear.json> <out.sql>
#
# Tier 1 armor and its vendor (the Chronal Quartermaster) stay with gen_class_sets.py. Everything here is
# rebuilt from scratch on each run: the SQL deletes its own id ranges first.
import json, math, os, subprocess, sys

cfg = json.load(open(sys.argv[1]))['server']['database']
cs  = json.load(open(sys.argv[2]))
tg  = json.load(open(sys.argv[3]))
out_path = sys.argv[4]
env = dict(os.environ, MYSQL_PWD=cfg['password'])
mysql = os.environ.get('MYSQL_EXE', r'C:\Program Files\MariaDB 12.3\bin\mysql.exe')


def query(sql):
    out = subprocess.run([mysql, '-h', cfg['host'], '-P', str(cfg['port']), '-u', cfg['username'], cfg['db'],
                          '-N', '-B', '-e', sql], env=env, capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines()]


def columns(table):
    return [r[0] for r in query(f"SELECT column_name FROM information_schema.columns WHERE table_schema = DATABASE() "
                                f"AND table_name = '{table}' ORDER BY ordinal_position")]


def quote(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "''") + "'"


def copy_row(table, cols, source_id, over):
    """INSERT ... SELECT copying one row, with some columns replaced by SQL expressions."""
    names = ', '.join(f'`{c}`' for c in cols)
    vals  = ', '.join(over.get(c, f'`{c}`') for c in cols)
    return f'INSERT INTO {table} ({names}) SELECT {vals} FROM {table} WHERE id = {source_id};'


item_cols  = columns('items')
spell_cols = columns('spells_new')
npc_cols   = columns('npc_types')
LOOK_COLS  = ['slots', 'material', 'icon', 'idfile', 'weight', 'size']
classes    = sorted((int(c), theme) for c, theme in cs['classes'].items())
tiers      = tg['tiers']
step       = tg['tier_item_step']

sql = ['-- Tiered rift gear. GENERATED by gen_tier_gear.py from class_sets.json + tier_gear.json',
       '-- New items and spells load into shared memory at server start: they appear after the next restart.', '',
       "-- Spell set bonuses (worn effect / proc / spell-cast proc). ALTER commits implicitly, so it runs before the transaction",
       "ALTER TABLE armor_set_bonuses ADD COLUMN IF NOT EXISTS `spell_id` INT(11) NOT NULL DEFAULT 0 AFTER `affix`;",
       "ALTER TABLE armor_set_bonuses ADD COLUMN IF NOT EXISTS `spell_type` TINYINT(3) UNSIGNED NOT NULL DEFAULT 0 "
       "COMMENT '1 worn effect, 2 melee proc, 3 spell-cast (sympathetic) proc' AFTER `spell_id`;", '',
       'START TRANSACTION;', '']

# ---------------------------------------------------------------------------------------------------
# Ids and cleanup
# ---------------------------------------------------------------------------------------------------
lo_item = tg['item_base']
hi_item = tg['item_base'] + step * len(tiers) - 1
spell_ids = {s['key']: tg['spell_id_base'] + n for n, s in enumerate(tg['custom_spells'])}
lo_spell, hi_spell = tg['spell_id_base'], tg['spell_id_base'] + len(tg['custom_spells']) - 1
v = tg['vendors']
lo_npc, hi_npc = v['npc_id_base'], v['npc_id_base'] + 3 * len(tiers) - 1

armor_sets  = [t['tier'] * 100 + c for t in tiers if t['tier'] > 1 for c, _ in classes]
nonvis_sets = [tg['nonvis_set_base'] + t['tier'] * 100 + c for t in tiers for c, _ in classes]
all_sets = ', '.join(str(s) for s in armor_sets + nonvis_sets)

sql += [
    f'DELETE FROM merchantlist WHERE merchantid BETWEEN {lo_npc} AND {hi_npc};',
    f'DELETE FROM spawn2 WHERE spawngroupID IN (SELECT spawngroupID FROM spawnentry WHERE npcID BETWEEN {lo_npc} AND {hi_npc});',
    f"DELETE FROM spawngroup WHERE name LIKE 'rift\\_tier\\_vendor\\_%';",
    f'DELETE FROM spawnentry WHERE npcID BETWEEN {lo_npc} AND {hi_npc};',
    f'DELETE FROM npc_types WHERE id BETWEEN {lo_npc} AND {hi_npc};',
    f'DELETE FROM armor_set_bonuses WHERE set_id IN ({all_sets});',
    f'DELETE FROM armor_set_items WHERE item_id BETWEEN {lo_item} AND {hi_item};',
    f'DELETE FROM dynamic_items WHERE item_id BETWEEN {lo_item} AND {hi_item};',
    f'DELETE FROM items WHERE id BETWEEN {lo_item} AND {hi_item};',
    f'DELETE FROM spells_new WHERE id BETWEEN {lo_spell} AND {hi_spell};',
    '',
]

# ---------------------------------------------------------------------------------------------------
# Custom spells (server-side only: set bonus worn effects and spell-cast triggers)
# ---------------------------------------------------------------------------------------------------
sql.append('-- Custom spells')
for s in tg['custom_spells']:
    over = {'id': str(spell_ids[s['key']]), 'name': quote(s['name'])}
    for slot, (eid, base, limit) in s['effects'].items():
        over[f'effectid{slot}'] = str(eid)
        over[f'effect_base_value{slot}'] = str(base)
        over[f'effect_limit_value{slot}'] = str(limit)
        over[f'max{slot}'] = '0'
    sql.append(copy_row('spells_new', spell_cols, s['copy'], over))
sql.append('')


def ladder_spell(ladder, tier):
    sid = tg['ladders'][ladder][tier - 1]
    return spell_ids[sid] if isinstance(sid, str) else sid


# ---------------------------------------------------------------------------------------------------
# Items
# ---------------------------------------------------------------------------------------------------
dynamic_rows, set_item_rows, bonus_rows, vendor_items = [], [], [], {}


def name_of(prefix, rest):
    return f'{prefix} {rest}'.strip()


def tier_item_id(tier, block, cid=0):
    return tg['item_base'] + (tier - 1) * step + block + cid


def scaled(value, mult):
    return max(1, round(value * mult)) if value > 0 else round(value * mult)


sql.append('-- Armor, gear tiers 2-5 (copies of the tier 1 class set pieces)')
for t in tiers:
    if t['tier'] == 1:
        continue
    vendor_items[('armor', t['tier'])] = []
    for cid, theme in classes:
        set_id = t['tier'] * 100 + cid
        for p in cs['pieces']:
            src = cs['item_id_base'] + p['block'] + cid
            iid = tier_item_id(t['tier'], p['block'], cid)
            name = name_of(t['prefix'], f"{theme} {p['name']}")
            sql.append(copy_row('items', item_cols, src, {'id': str(iid), 'Name': quote(name), 'lore': quote(name)}))
            dynamic_rows.append((iid, cid, t['tier'], round(p['stat_multiplier'] * t['mult'], 4), 'Class set piece'))
            set_item_rows.append((iid, set_id))
            vendor_items[('armor', t['tier'])].append((iid, 1 << (cid - 1)))
        for b in cs['bonuses'].get(str(cid), []):
            bonus_rows.append((set_id, b['pieces'], b.get('stat_id', 0), b.get('affix', ''), scaled(b['value'], t['mult']), 0, 0))
sql.append('')

sql.append('-- Non-visible pieces, gear tiers 1-5')
for t in tiers:
    vendor_items[('nonvis', t['tier'])] = []
    for cid, theme in classes:
        set_id = tg['nonvis_set_base'] + t['tier'] * 100 + cid
        for p in tg['nonvis_pieces']:
            iid = tier_item_id(t['tier'], p['block'], cid)
            name = name_of(t['prefix'], f"{theme} {p['name']}")
            over = {'id': str(iid), 'Name': quote(name), 'lore': quote(name), 'classes': str(1 << (cid - 1)),
                    'augslot6type': '0', 'augslot6visible': '0'}  # no ornament slot: jewelry has no visible model
            for c in LOOK_COLS:
                over[c] = f'(SELECT `{c}` FROM (SELECT * FROM items WHERE id = {p["look_item"]}) look)'
            sql.append(copy_row('items', item_cols, tg['nonvis_look_shell'], over))
            dynamic_rows.append((iid, cid, t['tier'], round(p['stat_multiplier'] * t['mult'], 4), 'Non-visible set piece'))
            set_item_rows.append((iid, set_id))
            vendor_items[('nonvis', t['tier'])].append((iid, 1 << (cid - 1)))

        nb = tg['nonvis_bonuses'][str(cid)]
        for affix, value in nb['three'].items():
            bonus_rows.append((set_id, 3, 0, affix, scaled(value, t['mult']), 0, 0))
        bonus_rows.append((set_id, 6, 0, '', 0, ladder_spell(nb['worn'], t['tier']), 1))
        bonus_rows.append((set_id, 9, 0, '', 0, ladder_spell(nb['proc'], t['tier']),
                           2 if nb['proc_type'] == 'proc' else 3))
sql.append('')

sql.append('-- Augments, gear tiers 1-5 (fixed stats, all classes, No Trade, aug types 1 and 2)')
for t in tiers:
    vendor_items[('augments', t['tier'])] = []
    for n, a in enumerate(tg['augments']):
        iid = tier_item_id(t['tier'], tg['augment_block'] + n)
        name = name_of(t['prefix'], a['name'])
        over = {'id': str(iid), 'Name': quote(name), 'lore': quote(name), 'itemtype': '54', 'augtype': '3',
                'slots': str(tg['augment_slots']), 'classes': '65535', 'races': '65535', 'icon': str(a['icon']),
                'price': '0'}
        for i in range(1, 7):
            over[f'augslot{i}type'] = '0'
            over[f'augslot{i}visible'] = '0'
        for stat, value in a['stats'].items():
            if stat not in item_cols:
                sys.exit(f'unknown items column {stat}')
            over[stat] = str(scaled(value, t['mult']))
        if 'focus' in a:
            over['focuseffect'] = str(a['focus'])
            over['focustype'] = '6'
        sql.append(copy_row('items', item_cols, tg['nonvis_look_shell'], over))
        vendor_items[('augments', t['tier'])].append((iid, 65535))  # merchantlist classes_required: all classes
sql.append('')

sql.append('INSERT INTO dynamic_items (item_id, class_id, tier, min_affixes, max_affixes, stat_multiplier, notes) VALUES')
sql.append(',\n'.join(f"({i}, {c}, {tier}, {cs['affixes']['min']}, {cs['affixes']['max']}, {m}, '{note}')"
                      for i, c, tier, m, note in dynamic_rows) + ';')
sql.append('INSERT INTO armor_set_items (item_id, set_id, class_mask) VALUES')
sql.append(',\n'.join(f'({i}, {s}, 0)' for i, s in set_item_rows) + ';')
sql.append('INSERT INTO armor_set_bonuses (set_id, min_pieces, class_mask, stat_id, affix, stat_value, spell_id, spell_type) VALUES')
sql.append(',\n'.join(f"({s}, {pc}, 0, {st}, '{af}', {val}, {sp}, {spt})" for s, pc, st, af, val, sp, spt in bonus_rows) + ';')
sql.append('')

# ---------------------------------------------------------------------------------------------------
# Vendors: three per tier (tier 1 armor is the existing Chronal Quartermaster)
# ---------------------------------------------------------------------------------------------------
sql.append('-- Tier vendors')
npc_id = v['npc_id_base']
placed = v.get('placed', {})
# Line order: tier by tier, kinds as listed; hand-placed vendors leave the line, so the rest spread out
order  = [(t['tier'], kind) for t in tiers for kind in v['kinds'] if f"{t['tier']}:{kind}" not in placed]
(sx, sy, sz), (ex, ey, _) = v['start'], v['end']


def spot(tier, kind):
    n = order.index((tier, kind)) / (len(order) - 1)
    return sx + (ex - sx) * n, sy + (ey - sy) * n


# EQ heading (0-512, x += sin, y += cos): the line's own heading, turned a quarter toward face_hint
line_h = math.degrees(math.atan2(ex - sx, ey - sy)) / 360 * 512
face   = min(((line_h + 128) % 512, (line_h - 128) % 512),
             key=lambda h: min(abs(h - v['face_hint']), 512 - abs(h - v['face_hint'])))
face   = round(face, 1)
def position(tier, kind):
    if f'{tier}:{kind}' in placed:
        return placed[f'{tier}:{kind}']
    x, y = spot(tier, kind)
    return [x, y, sz, face]


# Zone:StateSavingOnShutdown restores saved NPC positions on boot, overriding spawn2: drop the vendors' saved
# state (takes effect only while thevoida is shut down, or the zone saves the old spots again on shutdown)
sql.append(f"DELETE FROM zone_state_spawns WHERE npc_id = {v['quartermaster_npc']} OR npc_id BETWEEN {lo_npc} AND {hi_npc};")
qx, qy, qz, qh = position(1, 'armor')
sql.append(f"UPDATE spawn2 SET zone = '{v['zone']}', x = {qx:.2f}, y = {qy:.2f}, z = {qz}, heading = {qh} "
           f"WHERE spawngroupID IN (SELECT spawngroupID FROM spawnentry WHERE npcID = {v['quartermaster_npc']});")
sql.append(f"UPDATE npc_types SET lastname = 'Tier 1 {v['kinds']['armor']['title']}' WHERE id = {v['quartermaster_npc']};")
for t in tiers:
    prefix = t['prefix'] or v['tier1_prefix']
    for kind, k in v['kinds'].items():
        if kind == 'armor' and t['tier'] == 1:
            continue
        nid = npc_id
        npc_id += 1
        name = f"{prefix}_{k['name']}"
        sql.append(copy_row('npc_types', npc_cols, v['copy_npc'], {
            'id': str(nid), 'name': quote(name), 'lastname': quote(f"Tier {t['tier']} {k['title']}"),
            'race': str(k['race']), 'size': str(k['size']), 'merchant_id': str(nid)}))
        sql.append(f"INSERT INTO spawngroup (name, spawn_limit) VALUES ('rift_tier_vendor_{nid}', 0);")
        sql.append(f'INSERT INTO spawnentry (spawngroupID, npcID, chance) VALUES (LAST_INSERT_ID(), {nid}, 100);')
        x, y, z, h = position(t['tier'], kind)
        sql.append(f"INSERT INTO spawn2 (spawngroupID, zone, version, x, y, z, heading, respawntime, variance) "
                   f"SELECT id, '{v['zone']}', 0, {x:.2f}, {y:.2f}, {z}, {h}, 60, 0 FROM spawngroup "
                   f"WHERE name = 'rift_tier_vendor_{nid}';")

        unlock = t['unlock'] + {'armor': 0, 'nonvis': tg['nonvis_unlock_offset'], 'augments': tg['augment_unlock_offset']}[kind]
        cost = k['cost'][t['tier'] - 1]
        rows = []
        for slot, (iid, class_bits) in enumerate(vendor_items[(kind, t['tier'])], start=1):
            rows.append(f"({nid}, {slot}, {iid}, {cost}, {class_bits}, '{tg['unlock_bucket']}', '{unlock}', 2)")
        sql.append('INSERT INTO merchantlist (merchantid, slot, item, alt_currency_cost, classes_required, '
                   'bucket_name, bucket_value, bucket_comparison) VALUES')
        sql.append(',\n'.join(rows) + ';')
sql += ['', 'COMMIT;']

open(out_path, 'w', newline='\n').write('\n'.join(sql) + '\n')
print(f'{len(dynamic_rows)} dynamic items, {sum(len(x) for k, x in vendor_items.items() if k[0] == "augments")} augments, '
      f'{len(bonus_rows)} set bonus rows, {len(tg["custom_spells"])} spells, {npc_id - v["npc_id_base"]} vendors -> {out_path}')
