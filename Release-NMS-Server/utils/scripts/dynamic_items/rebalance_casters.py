# Rebalances the pure casters' guaranteed dynamic_affix_pool lines against a caster best-in-slot capture
# (Necro/Ench/Mage, #dyninfo worn, 8 visible slots, 2026-10-24). rebalance_to_bis.py measured melee gear and
# added the same flat amount to every class, which left casters short on INT / STA / Spell Damage and far
# over on STR / DEX / AGI / AC. Targets are ~122% of the capture, as for melee.
#
# INT casters (NEC, WIZ, MAG, ENC) get the INT / Spell Damage targets; priests (CLR, DRU, SHM) mirror them
# on WIS / Heal Amount and keep Spell Damage at 350 so they can solo. AC is cut by one factor for every
# caster, so plate / chain / leather priests keep their lead over cloth. Resists, HP, Mana, heroic INT/WIS
# and crits are unchanged.
#
#   python rebalance_casters.py <eqemu_config.json> [--sql out.sql]
import json, os, subprocess, sys

SLOTS = 7.8                  # summed stat_multiplier of the 8 visible tier 1 pieces (2 bracers)
AC_FACTOR = 420 / 655        # cloth caster AC from 655 to the 420 target

INT_CASTERS = (11, 12, 13, 14)
PRIESTS = (2, 6, 10)

# affix: (target total over the 8 pieces, spread around the per-piece average)
SHARED = {
    'sta':        (400, 0.15),
    'cha':        (220, 0.12),
    'str':        (85, 0.12),
    'heroic_str': (20, 0.25),
    'dex':        (200, 0.08),
    'agi':        (200, 0.08),
    'attack':     (100, 0.12),
}
INT_ONLY = {
    'int':      (480, 0.16),
    'spelldmg': (480, 0.24),
}
PRIEST_ONLY = {
    'wis':      (480, 0.16),
    'healamt':  (480, 0.24),
    'spelldmg': (350, 0.18),
}
# Class leads that stay: Enchanter CHA, and the Cleric / Shaman STR edge over the other casters
OVERRIDES = {
    (14, 'cha'):        (375, 0.17),
    (2, 'str'):         (100, 0.12),
    (10, 'str'):        (100, 0.12),
    (2, 'heroic_str'):  (37, 0.2),
    (10, 'heroic_str'): (37, 0.2),
}
HP_REGEN = (0, 3)            # a line that can roll 0: about 12 over 8 pieces


def band(total, spread):
    avg = total / SLOTS
    lo, hi = round(avg * (1 - spread)), round(avg * (1 + spread))
    return max(lo, 1), max(hi, lo, 1)


cfg = json.load(open(sys.argv[1]))['server']['database']
env = dict(os.environ, MYSQL_PWD=cfg['password'])
mysql = r'C:\Program Files\MariaDB 12.3\bin\mysql.exe'
out = subprocess.run([mysql, '-h', cfg['host'], '-P', str(cfg['port']), '-u', cfg['username'], cfg['db'], '-N',
                      '-B', '-e', "SELECT class_id, affix, min_value, max_value FROM dynamic_affix_pool "
                                  "WHERE guaranteed = 1 AND class_id IN (2, 6, 10, 11, 12, 13, 14)"],
                     env=env, capture_output=True, text=True, check=True).stdout
pool = {(int(c), a): (int(lo), int(hi)) for c, a, lo, hi in (l.split('\t') for l in out.splitlines())}

changes = {}
for cls in INT_CASTERS + PRIESTS:
    targets = dict(SHARED, **(INT_ONLY if cls in INT_CASTERS else PRIEST_ONLY))
    for affix, (total, spread) in targets.items():
        total, spread = OVERRIDES.get((cls, affix), (total, spread))
        changes[(cls, affix)] = band(total, spread)
    changes[(cls, 'hp_regen')] = HP_REGEN
    lo, hi = pool[(cls, 'ac')]
    changes[(cls, 'ac')] = (round(lo * AC_FACTOR), round(hi * AC_FACTOR))

names = {2: 'CLR', 6: 'DRU', 10: 'SHM', 11: 'NEC', 12: 'WIZ', 13: 'MAG', 14: 'ENC'}
sql = ['-- Caster rebalance against a caster best-in-slot capture. GENERATED by rebalance_casters.py']
for (cls, affix), (lo, hi) in sorted(changes.items()):
    old = pool[(cls, affix)]
    new_avg, old_avg = (lo + hi) / 2 * SLOTS, sum(old) / 2 * SLOTS
    print(f'{names[cls]} {affix:11} {old[0]:4}-{old[1]:<4} -> {lo:4}-{hi:<4}  set avg {old_avg:6.0f} -> {new_avg:6.0f}')
    sql.append(f"UPDATE dynamic_affix_pool SET min_value = {lo}, max_value = {hi} "
               f"WHERE class_id = {cls} AND affix = '{affix}' AND guaranteed = 1;")

if '--sql' in sys.argv:
    path = sys.argv[sys.argv.index('--sql') + 1]
    open(path, 'w', newline='\n').write('\n'.join(sql) + '\n')
    print('wrote', path)
